import {
  writeFileSync,
  mkdirSync,
  existsSync,
  readFileSync,
  rmSync,
} from "fs";
import { optimize } from "svgo";

const API_URL = "https://api.hyperliquid.xyz/info";
const CDN_URL = "https://app.hyperliquid.xyz/coins";
const OUTPUT_DIR = "svgs";
const ASSETS_FILE = "assets.json";
const GENERATED_DIR = "src/assets";
const CONCURRENCY = 3;
const REQUEST_DELAY_MS = 3000;

const argv = process.argv.slice(2);
const fromApi = argv.includes("--live");
const force = argv.includes("--force");
const onlyCached = argv.includes("--cached");

const sleep = (ms: number) => new Promise((r) => setTimeout(r, ms));

function sanitize(name: string): string {
  return name.replace(/[^a-zA-Z0-9_]/g, "_");
}

async function fetchApi<T>(body: object): Promise<T> {
  const res = await fetch(API_URL, {
    method: "POST",
    headers: { "Content-Type": "application/json" },
    body: JSON.stringify(body),
  });
  return res.json();
}

async function fetchAssetList(): Promise<string[]> {
  const [spotData, perpData] = await Promise.all([
    fetchApi<{ tokens: { name: string }[] }>({ type: "spotMeta" }),
    fetchApi<{ universe: { name: string }[] }>({ type: "meta" }),
  ]);
  const spot = spotData.tokens.map((t) => t.name);
  const perp = perpData.universe.map((u) => u.name);
  const combined = [...new Set([...spot, ...perp])];
  writeFileSync(ASSETS_FILE, JSON.stringify(combined, null, 2));
  return combined;
}

function guessVariants(asset: string): string[] {
  const candidates = [asset];
  if (asset.startsWith("k")) candidates.push(asset.slice(1));
  return [...new Set(candidates)];
}

async function downloadOne(asset: string): Promise<string | null> {
  for (const variant of guessVariants(asset)) {
    const url = `${CDN_URL}/${variant}.svg`;
    try {
      const res = await fetch(url);
      if (!res.ok) continue;
      const svg = await res.text();
      if (svg.includes("<svg")) return svg;
    } catch {
      continue;
    }
  }
  return null;
}

/**
 * Minify an SVG with SVGO. Falls back to the original markup if SVGO ever
 * throws or returns something that no longer looks like an SVG.
 */
function minify(svg: string): string {
  try {
    const { data } = optimize(svg, {
      multipass: true,
      plugins: [
        {
          name: "preset-default",
          params: {
            overrides: {
              // Keep ids: some HyperLiquid icons reference them via url(#id).
              cleanupIds: false,
            },
          },
        },
      ],
    });
    return data.includes("<svg") ? data : svg;
  } catch {
    return svg;
  }
}

function cachedPath(asset: string): string {
  return `${OUTPUT_DIR}/${sanitize(asset)}.svg`;
}

/** Returns every asset -> minified SVG string, reusing local files when possible. */
async function collectAll(assets: string[]): Promise<Map<string, string>> {
  if (!existsSync(OUTPUT_DIR)) mkdirSync(OUTPUT_DIR, { recursive: true });

  const map = new Map<string, string>();
  const queue = [...assets];
  let done = 0;

  await Promise.all(
    Array.from({ length: CONCURRENCY }, async () => {
      while (queue.length) {
        const asset = queue.shift()!;
        const file = cachedPath(asset);

        let raw: string | null = null;
        if (!force && existsSync(file)) {
          raw = readFileSync(file, "utf-8");
        } else if (onlyCached) {
          // Regenerate sources from the SVGs already on disk, no network.
          raw = null;
        } else {
          await sleep(REQUEST_DELAY_MS);
          raw = await downloadOne(asset);
        }

        if (raw) {
          const svg = minify(raw);
          map.set(asset, svg);
          writeFileSync(file, svg);
        }
        done++;
        process.stdout.write(`\r${done}/${assets.length} (${map.size} ok)`);
      }
    }),
  );

  console.log();
  return map;
}

function escapeSvg(svg: string): string {
  return svg
    .replace(/\\/g, "\\\\")
    .replace(/`/g, "\\`")
    .replace(/\$/g, "\\$");
}

function generateSources(map: Map<string, string>, allAssets: string[]) {
  // Only keep assets we actually have an SVG for, preserving source order.
  const available = allAssets.filter((a) => map.has(a));

  // Reset the generated assets folder so removed coins don't linger.
  rmSync(GENERATED_DIR, { recursive: true, force: true });
  mkdirSync(GENERATED_DIR, { recursive: true });

  const header = "// Auto-generated by scripts/fetch-svgs.ts — do not edit by hand.\n";

  // 1. One tiny module per asset (import only what you need).
  for (const asset of available) {
    const file = `${GENERATED_DIR}/${sanitize(asset)}.ts`;
    const body =
      `${header}const svg: string = \`${escapeSvg(map.get(asset)!)}\`;\n` +
      `export = svg;\n`;
    writeFileSync(file, body);
  }

  // 2. Light list of available asset names (+ case-insensitive lookup index).
  const indexEntries = available
    .map((asset) => `  ${JSON.stringify(asset.toUpperCase())}: ${JSON.stringify(asset)},`)
    .join("\n");
  writeFileSync(
    "src/names.ts",
    `${header}export const assets: readonly string[] = ${JSON.stringify(
      available,
      null,
      2,
    )};\n\n` +
      `/** Uppercase symbol -> canonical symbol (e.g. "KPEPE" -> "kPEPE"). */\n` +
      `export const assetIndex: Record<string, string> = {\n${indexEntries}\n};\n`,
  );

  // 3. Lazy loaders: one dynamic import per asset, so bundlers can code-split
  //    and Node only reads the file that is actually requested.
  const loaderEntries = available
    .map(
      (asset) =>
        `  ${JSON.stringify(asset)}: () => import("./assets/${sanitize(asset)}").then((m) => m.default),`,
    )
    .join("\n");
  writeFileSync(
    "src/loaders.ts",
    `${header}import type { AssetLoader } from "./types";\n\n` +
      `export const loaders: Record<string, AssetLoader> = {\n${loaderEntries}\n};\n`,
  );

  // 4. Opt-in heavy map (import all SVGs at once) for dynamic lookups by name.
  const imports = available
    .map((asset) => `import _${sanitize(asset)} from "./assets/${sanitize(asset)}";`)
    .join("\n");
  const mapEntries = available
    .map((asset) => `  ${JSON.stringify(asset)}: _${sanitize(asset)},`)
    .join("\n");
  writeFileSync(
    "src/svgMap.ts",
    `${header}${imports}\n\n` +
      `export { assets } from "./names";\n\n` +
      `import { resolveAsset } from "./resolve";\n\n` +
      `export const svgMap: Record<string, string> = {\n${mapEntries}\n};\n\n` +
      `export function getAssetSvg(asset: string): string | undefined {\n` +
      `  const name = resolveAsset(asset);\n` +
      `  return name ? svgMap[name] : undefined;\n}\n`,
  );

  console.log(
    `Generated ${available.length} modules in ${GENERATED_DIR}, plus names.ts, loaders.ts, svgMap.ts`,
  );
}

async function main() {
  const allAssets = fromApi
    ? await fetchAssetList()
    : (JSON.parse(readFileSync(ASSETS_FILE, "utf-8")) as string[]);
  console.log(`Found ${allAssets.length} assets (force=${force})`);

  console.log("Collecting/minifying SVGs...");
  const map = await collectAll(allAssets);
  console.log(`Success: ${map.size}/${allAssets.length}`);

  console.log("Generating sources...");
  generateSources(map, allAssets);

  console.log("Done!");
}

main();
