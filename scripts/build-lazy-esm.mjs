// Post-build step: emit an ESM version of the lazy entry point.
//
// The main package is CommonJS, where TypeScript downlevels `import()` to
// `require()` — so bundlers cannot code-split the lazy loaders. This file keeps
// real dynamic `import()` calls (one literal specifier per asset) so Rollup /
// esbuild / webpack can emit one chunk per icon. It only references the
// already-built CJS asset modules, so no SVG data is duplicated.
import { createRequire } from "node:module";
import { writeFileSync } from "node:fs";
import { fileURLToPath } from "node:url";
import { dirname, join } from "node:path";

const require = createRequire(import.meta.url);
const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const { assets, assetIndex } = require(join(root, "dist", "names.js"));

const loaderEntries = assets
  .map(
    (asset) =>
      `  ${JSON.stringify(asset)}: () => import("./assets/${asset}.js").then((m) => m.default),`,
  )
  .join("\n");

const indexEntries = Object.entries(assetIndex)
  .map(([key, value]) => `  ${JSON.stringify(key)}: ${JSON.stringify(value)},`)
  .join("\n");

const code = `// Auto-generated by scripts/build-lazy-esm.mjs — do not edit by hand.
import { assets } from "./names.js";

export { assets };

const assetIndex = {
${indexEntries}
};

/** Uppercase symbol -> canonical symbol (e.g. "KPEPE" -> "kPEPE"). */
function resolveAsset(asset) {
  return Object.prototype.hasOwnProperty.call(assetIndex, asset.toUpperCase())
    ? assetIndex[asset.toUpperCase()]
    : undefined;
}

export { resolveAsset };

const loaders = {
${loaderEntries}
};

/** Does this package ship an inline SVG for \`asset\`? Case-insensitive. */
export function hasAsset(asset) {
  return resolveAsset(asset) !== undefined;
}

/**
 * Lazily load a single asset's inline SVG (one dynamic import per asset).
 * @returns {Promise<string | undefined>}
 */
export async function loadAsset(asset) {
  const name = resolveAsset(asset);
  return name ? loaders[name]() : undefined;
}
`;

writeFileSync(join(root, "dist", "lazy.mjs"), code);
console.log(`Generated dist/lazy.mjs (${assets.length} lazy loaders)`);
